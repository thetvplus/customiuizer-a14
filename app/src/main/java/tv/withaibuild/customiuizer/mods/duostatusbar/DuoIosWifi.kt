    fun paths(bold: Boolean,small: Boolean=false): Array<Path> =
        if(small) { if(bold) smallHeavy else smallRegular } else if(bold) heavy else regular
    private fun build(bold: Boolean,small: Boolean): Array<Path> {
        val data=if(bold) blackPaths() else boldPaths()
        val viewport=if(bold) RectF(0f,0f,BLACK_WIDTH,BLACK_HEIGHT) else RectF(0f,0f,BOLD_WIDTH,BOLD_HEIGHT)
        val w=width(bold,small); val h=height(bold,small)
        val x=60f-w*.5f
        // The native top is a measured symbol-frame anchor. For the standalone
        // Android path, centre its visible ink on the ring (also Status Trio's
        // anchoring rule), rather than treating the font-frame top as ink top.
        val y=inkTop(bold,small)
        val fit=Matrix().apply { setRectToRect(viewport,RectF(x,y,x+w,y+h),Matrix.ScaleToFit.CENTER) }
        for(path in data) path.transform(fit)
        return data
    }
