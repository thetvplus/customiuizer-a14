    // A 16-point font request is not a 16-point ink width. Keep the iPhone
    // silhouette proportions; the secondary branch requests 15 points.
    private fun factor(small: Boolean) = (if(small) 15f else 16f)/17f*120f/47f
    private fun width(bold: Boolean,small: Boolean) = (if(bold) BLACK_WIDTH else BOLD_WIDTH)*factor(small)
    private fun height(bold: Boolean,small: Boolean) = (if(bold) BLACK_HEIGHT else BOLD_HEIGHT)*factor(small)
    fun top(small: Boolean) = (if(small) 13f else 15.33f)*120f/47f
    private fun inkTop(bold: Boolean,small: Boolean) = if(small) top(true) else 60f-height(bold,false)*.5f
    fun layoutBottom(bold: Boolean,small: Boolean=false) = inkTop(bold,small)+height(bold,small)
    private val regular by lazy(LazyThreadSafetyMode.NONE) { build(false,false) }
    private val heavy by lazy(LazyThreadSafetyMode.NONE) { build(true,false) }
